def text(img, x, y, s, col, shadow=None):
    """Tulis teks; kembalikan lebar."""
    cx = x
    for ch in s.upper():
        g = G.get(ch, G['?'])
        for i, c in enumerate(g):
            if c == '#':
                px, py = cx + i % 5, y + i // 5
                if shadow:
                    img.putpixel((px + 1, py + 1), shadow)
        for i, c in enumerate(g):
            if c == '#':
                img.putpixel((cx + i % 5, y + i // 5), col)
        cx += 6 if ch != ' ' else 4
    return cx - x
